/**
 * Bundle a labelled CSV into the web app so the ML engine trains on it automatically.
 *
 *   node backend/build-dataset.js data/my_dataset.csv
 *
 * CSV needs a "text" column and a "label" column (Positive / Negative / Neutral,
 * or pos/neg/neu, or 1/-1/0). Writes js/dataset.js.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { normalizeLabel } = require("../js/ml.js");

function parseCSV(text) {
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim()));
}

const input = process.argv[2] || path.join(__dirname, "..", "data", "sample_hinglish_dataset.csv");
const isSample = /sample_hinglish_dataset\.csv$/.test(input);
const raw = fs.readFileSync(input, "utf8").replace(/^﻿/, "");
const table = parseCSV(raw);
const header = table[0].map((h) => h.trim().toLowerCase());
const ti = header.indexOf("text");
const li = header.indexOf("label");
const di = header.indexOf("domain");
if (ti < 0 || li < 0) {
  console.error('CSV must have "text" and "label" columns. Found: ' + header.join(", "));
  process.exit(1);
}
const rows = [];
let skipped = 0;
for (const r of table.slice(1)) {
  const text = (r[ti] || "").trim();
  const label = normalizeLabel(r[li]);
  if (!text || !label) { skipped++; continue; }
  rows.push([text, label, di >= 0 ? (r[di] || "").trim() : ""]);
}
const counts = rows.reduce((a, r) => ((a[r[1]] = (a[r[1]] || 0) + 1), a), {});
const out = path.join(__dirname, "..", "js", "dataset.js");
const banner = `/* Generated by backend/build-dataset.js from ${path.basename(input)} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand. */\n`;
fs.writeFileSync(
  out,
  banner + "window.NP_DATASET = " + JSON.stringify({ name: path.basename(input), sample: isSample, counts, rows }) + ";\n"
);
console.log(`Wrote ${rows.length} rows to js/dataset.js`, counts, skipped ? `(skipped ${skipped} invalid rows)` : "");
